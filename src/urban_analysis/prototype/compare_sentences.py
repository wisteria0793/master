import numpy as np
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity

# 比較対象のモデル
# Multilingual-E5 (passage プレフィックスを使用) と Sentence-BERT を比較
MODELS = {
    "Multilingual-E5 (passage-passage)": "intfloat/multilingual-e5-base",
    "Sentence-BERT (Japanese)": "sonoisa/sentence-bert-base-ja-mean-tokens-v2"
}

def calculate_similarity(model_name, text1, text2, use_e5_prefix=False):
    print(f"モデル '{model_name}' を読み込み中...")
    model = SentenceTransformer(model_name)

    # E5の場合、長文同士の比較なら両方に "passage: " を付けるのが推奨される
    # これにより「質問」ではなく「説明文」としての意味内容を比較します
    t1 = f"passage: {text1}" if use_e5_prefix else text1
    t2 = f"passage: {text2}" if use_e5_prefix else text2

    print(f"ベクトル化を実行中...")
    embeddings = model.encode([t1, t2], normalize_embeddings=True)
    
    sim = cosine_similarity([embeddings[0]], [embeddings[1]])[0][0]
    return sim

